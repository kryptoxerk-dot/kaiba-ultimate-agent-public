def test_a_portal_revert_survives_the_transport_as_a_revert(rpc):
    """The root cause. The real captured revert item, through the real json_rpc_batch."""
    tok = token("POOL")
    call = (evm_price.FLAP_PORTAL, _portal_data(tok))
    keep = _keep_reverts_transport()([call])
    assert keep[0] is not None, "a revert must not read as a dead endpoint"
    assert keep[0].selector == "0xde6137d1"
    assert keep[0].address_arg(0) == tok
    # Every existing caller (protection included) is unchanged: a revert is still None.
    assert evm_price.json_rpc_batch(BSC)([call]) == [None]


