class CapturedChain:
    """A fake RPC that answers the captured items, and records what it was asked."""

    def __init__(self) -> None:
        self.answers: dict[tuple[str, str], dict] = {}
        for _tok, rows in CAPTURED.values():
            for to, data, item in rows:
                self.answers[(to.lower(), data.lower())] = copy.deepcopy(item)
        self.batches: list[int] = []
        self.down = False  # True: every request fails at the transport (a 429, a timeout)

    def post_json(self, provider, endpoint, url, *, json_body, **kw):
        self.batches.append(len(json_body))
        if self.down:
            return SimpleNamespace(ok=False, data=None)
        out = []
        for call in json_body:
            key = (call["params"][0]["to"].lower(), call["params"][0]["data"].lower())
            # Anything not captured (the Flap Buy Quota read, say) reverts with no data.
            item = self.answers.get(key, {"error": {"code": 3, "message": "execution reverted"}})
            out.append({"jsonrpc": "2.0", "id": call["id"], **copy.deepcopy(item)})
        return SimpleNamespace(ok=True, data=out)


