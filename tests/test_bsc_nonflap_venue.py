def _bump_word(item: dict, word: int, by: int) -> None:
    body = item["result"][2:]
    value = int(body[word * 64:(word + 1) * 64], 16) + by
    item["result"] = "0x" + body[:word * 64] + format(value, "064x") + body[(word + 1) * 64:]


@pytest.mark.parametrize(
    ("index", "word", "by", "expected"),
    [
        (2, 2, 10**21, "fourmeme_try_buy_disagrees"),             # tryBuy amount, +0.16%
        (0, 3, 10**6, "fourmeme_price_disagrees"),                # helper lastPrice
        (1, 9, 10**6, "fourmeme_record_disagrees_with_helper"),   # manager lastPrice
    ],
)
def test_a_curve_that_fails_its_cross_checks_refuses(rpc, tmp_db, pairs, index, word, by, expected):
    """Tamper one captured word: the read must refuse, and the ladder must stop."""
    tok = token("CURVE_BNB")
    to, data = evm_price._non_flap_calls(tok)[index]
    _bump_word(rpc.answers[(to, data)], word, by)
    if index == 0:
        # lastPrice is read twice; move both so only the derived-price check can catch it.
        to1, data1 = evm_price._non_flap_calls(tok)[1]
        _bump_word(rpc.answers[(to1, data1)], 9, by)
    ready(tmp_db, tok, liquidity_usd="250000")
    venue = read_venue(BSC, tok, tmp_db)
    assert not venue.priced
    assert venue.note.startswith(f"{BSC_VENUE_UNAVAILABLE}{expected}"), venue.note
    assert isinstance(resolve_depth(BSC, tok, tmp_db), NoDepth)
    assert pairs == []


