def _measure(value: str | None) -> dict:
    if value is None:
        return {"value": None, "basis": "unavailable", "receipt": None, "freshness_budget_s": 900}
    return {"value": value, "basis": "provider_reported",
            "receipt": {"provider": "gmgn", "endpoint": "token.security",
                        "observed_at_ms": now_ms(), "basis": "provider_reported"},
            "freshness_budget_s": 900}


def ready(conn, tok: str, *, tax_bps: str = "0", liquidity_usd: str | None = None) -> None:
    conn.execute(
        "INSERT OR REPLACE INTO native_prices (chain, ts_ms, price_usd, source, receipt_json) "
        "VALUES (?,?,?,?,?)", (BSC.value, now_ms(), BNB_USD, "dexscreener", "{}"),
    )
    body = {"address": tok, "chain": BSC.value, "built_at_ms": now_ms(), "grade": "B",
            "buy_tax_bps": _measure(tax_bps), "sell_tax_bps": _measure(tax_bps),
            "liquidity_usd": _measure(liquidity_usd)}
    conn.execute(
        "INSERT OR REPLACE INTO token_dossiers (chain, address, built_at_ms, score, grade, "
        "blockers_json, warnings_json, unknowns_json, dossier_json) VALUES (?,?,?,?,?,?,?,?,?)",
        (BSC.value, tok, now_ms(), None, "B", "[]", "[]", "[]", json.dumps(body)),
    )
    conn.commit()


def _portal_data(tok: str) -> str:
    return evm_price.SEL_GET_TOKEN_V8_SAFE + tok[2:].lower().rjust(64, "0")


def _revert_for(tok: str) -> dict:
    return {"error": {"code": 3, "message": "execution reverted",
                      "data": "0xde6137d1" + tok[2:].lower().rjust(64, "0")}}


def _keep_reverts_transport():
    return evm_price.json_rpc_batch(BSC, keep_reverts=True)


